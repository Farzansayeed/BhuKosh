const STORAGE_KEY = 'bhukosh.lang'

function loadLang() {
  try {
    const v = localStorage.getItem(STORAGE_KEY)
    return LANGS.some((l) => l.code === v) ? v : 'en'
  } catch {
    return 'en'
  }
}

